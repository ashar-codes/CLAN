// File-transfer benchmark. Real server (child process) + N simulated students using the real client download path
// (Range-capable HTTP stream, incremental SHA-256, atomic rename). Rewrites the generated block in docs/BENCHMARKS.md.
// Usage: node tools/sim/bench-files.ts [--host 192.168.1.20] [--runs 3] [--no-write]
import { fork } from 'node:child_process';
import { randomBytes, randomUUID } from 'node:crypto';
import { appendFileSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, tmpdir, totalmem } from 'node:os';
import { join } from 'node:path';
import { parseArgs } from 'node:util';
import { formatBytes, joinByCode } from '@classroom/client';
import { downloadResource } from '@classroom/client/node';
import type { ResourceView } from '@classroom/protocol';
import { candidateInterfaces } from '@classroom/server';

const { values } = parseArgs({ options: { host: { type: 'string' }, runs: { type: 'string', default: '3' }, 'no-write': { type: 'boolean' } } });
const host = values.host ?? candidateInterfaces()[0]?.address ?? '127.0.0.1';
const MB = 1024 * 1024;
const SCENARIOS: [clients: number, bytes: number][] = [[1, MB], [1, 10 * MB], [1, 100 * MB], [10, MB], [20, MB], [40, MB], [40, 10 * MB]];
const pct = (xs: number[], p: number) => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.ceil((p / 100) * s.length) - 1)]!; };

const genDir = mkdtempSync(join(tmpdir(), 'bench-gen-'));
const files = [MB, 10 * MB, 100 * MB].map((size) => {
  const p = join(genDir, `file-${size}.bin`);
  writeFileSync(p, '');
  for (let off = 0; off < size; off += MB) appendFileSync(p, randomBytes(Math.min(MB, size - off)));
  return p;
});
const child = fork(new URL('./bench-server.ts', import.meta.url), [host, files.join(',')], { stdio: 'inherit' });
const ask = <T>(t: string) => new Promise<T>((res) => { child.once('message', res as never); child.send({ t }); });
const ready = await new Promise<{ url: string; code: string; resources: ResourceView[] }>((res) => child.once('message', res as never));
type Stats = { cpu: NodeJS.CpuUsage; maxRssKb: number };

async function scenario(n: number, bytes: number) {
  const resource = ready.resources.find((r) => r.size === bytes)!;
  const students = await Promise.all(Array.from({ length: n }, (_, i) => joinByCode([{ url: ready.url }], ready.code, { fullName: `Bench ${i}`, rollNo: `B-${i}`, deviceName: `bench-${i}`, deviceId: randomUUID() })));
  const dirs = students.map(() => mkdtempSync(join(tmpdir(), 'bench-cli-')));
  const before = await ask<Stats>('stats');
  const t0 = performance.now();
  const results = await Promise.all(students.map(async (s, i) => {
    const start = performance.now();
    try {
      await downloadResource({ url: ready.url, token: s.token, resource, destDir: dirs[i]! });
      return { ok: true, ms: performance.now() - start, hashFail: false };
    } catch (e) {
      return { ok: false, ms: performance.now() - start, hashFail: (e as { code?: string }).code === 'hash_mismatch' };
    }
  }));
  const elapsed = performance.now() - t0;
  const after = await ask<Stats>('stats');
  dirs.forEach((d) => rmSync(d, { recursive: true, force: true }));
  const ms = results.filter((r) => r.ok).map((r) => r.ms);
  const cpuMs = (after.cpu.user + after.cpu.system - before.cpu.user - before.cpu.system) / 1000;
  return {
    n, bytes, elapsed, ok: ms.length, hashFails: results.filter((r) => r.hashFail).length,
    p50: pct(ms, 50), p95: pct(ms, 95), throughput: (ms.length * bytes) / (elapsed / 1000),
    cpuPct: (cpuMs / elapsed) * 100, peakRssMb: after.maxRssKb / 1024,
  };
}

const rows = [];
for (const [n, bytes] of SCENARIOS) {
  const runs = [];
  for (let r = 0; r < Number(values.runs); r++) runs.push(await scenario(n, bytes));
  runs.sort((a, b) => a.elapsed - b.elapsed);
  const median = runs[Math.floor(runs.length / 2)]!;
  rows.push(median);
  console.log(`${n} x ${formatBytes(bytes)}: ${median.elapsed.toFixed(0)} ms, ${median.ok}/${n} ok`);
}
await new Promise((r) => { child.once('exit', r); child.send({ t: 'stop' }); });
rmSync(genDir, { recursive: true, force: true });

const fmtMs = (x: number) => (x < 1000 ? `${x.toFixed(0)} ms` : `${(x / 1000).toFixed(2)} s`);
const block = [
  `Generated by \`pnpm benchmark\` on ${new Date().toISOString()}.`,
  '',
  '**Environment.** ' + `${platform()} ${release()}, ${cpus()[0]?.model} ×${cpus().length}, ${(totalmem() / 1e9).toFixed(0)} GB RAM, Node ${process.version}. ` +
    `Server bound to \`${host}\` (this machine's LAN interface) in its own process; all simulated students run in one other process on the **same machine**.`,
  '',
  `**Method.** Each student joins (open policy) and downloads with the production client path: streamed HTTP, incremental SHA-256, \`.partial\` file, verify, atomic rename. ` +
    `Each scenario runs ${values.runs}× and the median-elapsed run is shown. Server CPU = server process CPU time ÷ wall time (100% = one core). Peak RSS = server process high-water mark so far (includes startup, importing the 1/10/100 MB test files, and earlier scenarios).`,
  '',
  '**Limitations.** Loopback-speed networking, no radio contention, no packet loss. Client hashing for all students shares one process, so many-client rows are partly client-bound. ' +
    '**These numbers do not demonstrate Wi-Fi performance**; use `tools/sim/lan-bench.ts` with real devices for that.',
  '',
  '| Clients × size | Total elapsed | p50 per client | p95 per client | Aggregate throughput | Success | Hash failures | Server CPU | Server peak RSS |',
  '|---|---:|---:|---:|---:|---:|---:|---:|---:|',
  ...rows.map((r) => `| ${r.n} × ${formatBytes(r.bytes)} | ${fmtMs(r.elapsed)} | ${fmtMs(r.p50)} | ${fmtMs(r.p95)} | ${formatBytes(r.throughput)}/s | ${r.ok}/${r.n} | ${r.hashFails} | ${r.cpuPct.toFixed(0)}% | ${r.peakRssMb.toFixed(0)} MB |`),
  '',
  `Targets (same-machine): 1 MB to one client < 2 s → **${fmtMs(rows[0]!.elapsed)}**; 40 × 1 MB < 10 s → **${fmtMs(rows.find((r) => r.n === 40 && r.bytes === MB)!.elapsed)}**.`,
].join('\n');
console.log(block);
if (!values['no-write']) {
  const path = new URL('../../docs/BENCHMARKS.md', import.meta.url);
  const doc = readFileSync(path, 'utf8');
  writeFileSync(path, doc.replace(/<!-- bench:files:start -->[\s\S]*<!-- bench:files:end -->/, `<!-- bench:files:start -->\n${block}\n<!-- bench:files:end -->`));
}
process.exit(0);
