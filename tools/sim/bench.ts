// Load simulator + benchmark. Spawns N simulated students using the real client library against a real server.
// Results are measured, never edited by hand: this script rewrites the generated block of docs/BENCHMARKS.md.
// Usage: node tools/sim/bench.ts [--host 192.168.1.20] [--no-write]
import { readFileSync, writeFileSync } from 'node:fs';
import { cpus, platform, release, totalmem } from 'node:os';
import { parseArgs } from 'node:util';
import * as opaque from '@serenity-kit/opaque';
import { ClassroomConnection, pairAndJoin } from '@classroom/client';
import { newEd25519, nodeSigner, pinnedTransport } from '@classroom/client/node';
import type { ServerMessage } from '@classroom/protocol';
import { candidateInterfaces, startClassroomServer } from '@classroom/server';

const { values } = parseArgs({ options: { host: { type: 'string' }, 'no-write': { type: 'boolean' } } });
const host = values.host ?? candidateInterfaces()[0]?.address ?? '127.0.0.1';
const pct = (xs: number[], p: number) => { const s = [...xs].sort((a, b) => a - b); return s[Math.min(s.length - 1, Math.floor((p / 100) * s.length))]!; };
const fmt = (ms: number) => `${ms.toFixed(1)} ms`;

async function run(n: number) {
  // All simulated students share one source IP, so the per-source pairing concurrency cap is raised here only.
  const s = await startClassroomServer({ title: `Bench ${n}`, host, limits: { pairInflightPerSource: 1000 } });
  const teacherMsgs: ((m: ServerMessage) => void)[] = [];
  await opaque.ready;
  const teacher = new ClassroomConnection(s.url, s.classroom.teacherToken, { onMessage: (m) => teacherMsgs.forEach((f) => f(m)) }, 5000, pinnedTransport(s.tls));
  await new Promise<void>((r) => teacherMsgs.push((m) => { if (m.t === 'hello') r(); }));

  // Teacher auto-approves as requests appear (measures the full request -> approved round trip).
  teacherMsgs.push((m) => { if (m.t === 'roster') for (const x of m.members) if (x.status === 'pending') teacher.send({ t: 'member.approve', memberId: x.id }); });

  const joinMs: number[] = [];
  const conns: ClassroomConnection[] = [];
  const t0 = performance.now();
  await Promise.all(Array.from({ length: n }, async (_, i) => {
    const start = performance.now();
    const j = await pairAndJoin({ candidates: [{ url: s.bootstrapUrl, sid: s.classroom.id }], code: s.classroom.code, profile: { fullName: `Sim ${i}`, rollNo: `SIM-${i}`, deviceName: `sim-${i}` }, device: nodeSigner(newEd25519().privatePkcs8), opaque: opaque.client, transportFor: pinnedTransport });
    await new Promise<void>((resolve) => {
      const c = new ClassroomConnection(j.url, j.token, {
        onMessage: (m) => { if ((m.t === 'hello' && m.status === 'approved') || (m.t === 'member.status' && m.status === 'approved')) resolve(); },
      }, 1_000_000, j.transport);
      conns.push(c);
    });
    joinMs.push(performance.now() - start);
  }));
  const allJoined = performance.now() - t0;

  // Event latency: teacher action -> every student receives the broadcast.
  const eventMs: number[] = [];
  for (let k = 0; k < 10; k++) {
    const locked = k % 2 === 0;
    const start = performance.now();
    let got = 0;
    await new Promise<void>((resolve) => {
      for (const c of conns) (c as unknown as { h: { onMessage: (m: ServerMessage) => void } }).h.onMessage = (m) => {
        if (m.t === 'class.state' && m.classroom.locked === locked) { eventMs.push(performance.now() - start); if (++got === n) resolve(); }
      };
      teacher.send({ t: 'class.lock', locked });
    });
  }
  const mem = process.memoryUsage().rss / 1e6;
  conns.forEach((c) => c.close());
  teacher.close();
  await s.close();
  return { n, joinP50: pct(joinMs, 50), joinP95: pct(joinMs, 95), allJoined, evP50: pct(eventMs, 50), evP95: pct(eventMs, 95), mem };
}

const rows = [];
for (const n of [1, 10, 20, 40]) rows.push(await run(n));

const table = [
  `Generated by \`pnpm benchmark\` on ${new Date().toISOString()}`,
  `Machine: ${platform()} ${release()}, ${cpus()[0]?.model} x${cpus().length}, ${(totalmem() / 1e9).toFixed(0)} GB, Node ${process.version}.`,
  `**Secure path (Milestone 2.5):** each join = OPAQUE pairing (Argon2id key stretching on the client) + TLS 1.3 + Ed25519 device proof. Server bound to ${host}. Simulated students run in the same process on the same machine and pair concurrently, so OPAQUE work for all students shares one CPU core — this measures server + protocol cost, **not Wi-Fi air time**.`,
  '',
  '| Students | Join→approved p50 | Join→approved p95 | All joined (wall) | Broadcast event p50 | Broadcast event p95 | Process RSS |',
  '|---:|---:|---:|---:|---:|---:|---:|',
  ...rows.map((r) => `| ${r.n} | ${fmt(r.joinP50)} | ${fmt(r.joinP95)} | ${fmt(r.allJoined)} | ${fmt(r.evP50)} | ${fmt(r.evP95)} | ${r.mem.toFixed(0)} MB |`),
].join('\n');
console.log(table);

if (!values['no-write']) {
  const path = new URL('../../docs/BENCHMARKS.md', import.meta.url);
  const doc = readFileSync(path, 'utf8');
  const out = doc.replace(/<!-- bench:join-secure:start -->[\s\S]*<!-- bench:join-secure:end -->/, `<!-- bench:join-secure:start -->\n${table}\n<!-- bench:join-secure:end -->`);
  writeFileSync(path, out);
}
process.exit(0);
